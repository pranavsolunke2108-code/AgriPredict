"""Alerts router: real-time notifications for weather risks and growth stage tasks."""

import logging
from typing import Any, Dict, List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status

from app import db
from app.db import DatabaseProcedureError
from app.dependencies import get_current_farmer, require_admin
from app.schemas import AlertResponse, MessageResponse, UnreadAlertCountResponse

logger = logging.getLogger("agripredict.alerts")
router = APIRouter(tags=["Alerts"])


@router.get(
    "/alerts",
    response_model=List[AlertResponse],
    summary="Get alerts for all farms owned by the farmer",
)
def get_farmer_alerts(
    unread: Optional[bool] = Query(False, description="Filter only unread alerts"),
    limit: int = Query(20, ge=1, le=100, description="Max alerts to return"),
    offset: int = Query(0, ge=0, description="Offset for pagination"),
    current_farmer: Dict[str, Any] = Depends(get_current_farmer),
):
    """Retrieve alerts generated by weather triggers and task schedulers.

    Filtered strictly to the authenticated farmer's farms, newest first.
    """
    farmer_id = current_farmer["farmer_id"]

    query = """
        SELECT
            a.alert_id,
            a.farm_id,
            f.farm_name,
            a.alert_type,
            a.message,
            a.created_at,
            a.is_read
        FROM alerts a
        JOIN farms f ON a.farm_id = f.farm_id
        WHERE f.farmer_id = %s
    """
    params: List[Any] = [farmer_id]

    if unread:
        query += " AND a.is_read = 0"

    query += " ORDER BY a.created_at DESC, a.alert_id DESC LIMIT %s OFFSET %s"
    params.extend([limit, offset])

    rows = db.fetch_all(query, tuple(params))

    return [
        AlertResponse(
            alert_id=int(r["alert_id"]),
            farm_id=int(r["farm_id"]),
            farm_name=r.get("farm_name"),
            alert_type=r["alert_type"],
            message=r["message"],
            created_at=r["created_at"],
            is_read=bool(r["is_read"]),
        )
        for r in rows
    ]


@router.get(
    "/alerts/unread-count",
    response_model=UnreadAlertCountResponse,
    summary="Get count of unread alerts for farmer",
)
def get_unread_alerts_count(
    current_farmer: Dict[str, Any] = Depends(get_current_farmer),
):
    """Retrieve count of unread notifications for navbar bell icon."""
    farmer_id = current_farmer["farmer_id"]

    query = """
        SELECT COUNT(*) AS total
        FROM alerts a
        JOIN farms f ON a.farm_id = f.farm_id
        WHERE f.farmer_id = %s AND a.is_read = 0
    """
    row = db.fetch_one(query, (farmer_id,))
    total = row["total"] if row else 0

    return UnreadAlertCountResponse(unread_count=int(total))


@router.patch(
    "/alerts/{alert_id}/read",
    response_model=MessageResponse,
    summary="Mark a specific alert as read",
)
def mark_alert_read(
    alert_id: int,
    current_farmer: Dict[str, Any] = Depends(get_current_farmer),
):
    """Mark an alert as read with farm ownership verification."""
    farmer_id = current_farmer["farmer_id"]

    query = """
        SELECT a.alert_id, f.farmer_id
        FROM alerts a
        JOIN farms f ON a.farm_id = f.farm_id
        WHERE a.alert_id = %s
    """
    row = db.fetch_one(query, (alert_id,))
    if not row:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Alert with ID {alert_id} not found",
        )
    if row["farmer_id"] != farmer_id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="You do not have permission to modify this alert",
        )

    db.execute_update("UPDATE alerts SET is_read = 1 WHERE alert_id = %s", (alert_id,))

    return MessageResponse(
        detail=f"Alert #{alert_id} marked as read",
        success=True,
    )


@router.post(
    "/alerts/read-all",
    response_model=MessageResponse,
    summary="Mark all alerts as read for the logged-in farmer",
)
def mark_all_alerts_read(
    current_farmer: Dict[str, Any] = Depends(get_current_farmer),
):
    """Mark all unread notifications as read across all farms owned by the farmer."""
    farmer_id = current_farmer["farmer_id"]

    # Compatible with both MySQL and SQLite
    update_query = """
        UPDATE alerts
        SET is_read = 1
        WHERE is_read = 0
          AND farm_id IN (SELECT farm_id FROM farms WHERE farmer_id = %s)
    """
    affected = db.execute_update(update_query, (farmer_id,))

    return MessageResponse(
        detail=f"Marked {affected} alert(s) as read",
        success=True,
    )


@router.post(
    "/admin/run-task-alerts",
    tags=["Admin"],
    summary="Admin: manually trigger task alerts generation procedure",
)
def admin_run_task_alerts(
    days_ahead: int = Query(2, ge=0, le=14),
    admin_farmer: Dict[str, Any] = Depends(require_admin),
):
    """Trigger generate_task_alerts(days_ahead) procedure manually. Requires admin privileges."""
    try:
        db.call_procedure("generate_task_alerts", (days_ahead,))
    except DatabaseProcedureError as exc:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=exc.message,
        )

    return {
        "detail": f"Task alerts generation executed successfully (window: {days_ahead} days ahead).",
        "days_ahead": days_ahead,
    }
